#[cfg(test)]
mod tests {
    use ironcalc::base::UserModel;

    #[test]
    fn every_name_is_a_function_the_engine_knows() {
        let lang = ironcalc::base::language::get_language("en").unwrap();
        let names = super::names(&lang.functions);
        assert!(names.len() > 400 && names.contains(&"SUM") && names.contains(&"XLOOKUP"));
        let mut m = UserModel::new_empty("t", "en", "UTC", "en").unwrap();
        let unknown: Vec<&str> = names
            .iter()
            .copied()
            .filter(|n| {
                m.set_user_input(0, 1, 1, &format!("={n}()")).unwrap();
                m.get_formatted_cell_value(0, 1, 1).unwrap() == "#NAME?"
            })
            .collect();
        assert!(unknown.is_empty(), "not functions: {unknown:?}");
    }
}
